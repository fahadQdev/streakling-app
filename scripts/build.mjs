// Builds the standalone web app (docs/index.html) from prototype/Main.dc.html.
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'prototype/Main.dc.html'), 'utf8');

function between(text, start, end, label) {
  const a = text.indexOf(start);
  const b = text.indexOf(end, a + start.length);
  if (a === -1 || b === -1) throw new Error('Could not find ' + label);
  return text.slice(a + start.length, b);
}

const xdc = between(src, '<x-dc>', '</x-dc>', '<x-dc> block');
const helmet = between(xdc, '<helmet>', '</helmet>', '<helmet> block');
const template = xdc.slice(xdc.indexOf('</helmet>') + '</helmet>'.length).trim();

const scriptTag = src.match(/<script type="text\/x-dc" data-dc-script data-props='([^']*)'>([\s\S]*?)<\/script>/);
if (!scriptTag) throw new Error('Could not find the logic script');
const decode = (s) => s.replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&');
const propSpec = JSON.parse(decode(scriptTag[1]));
const props = {};
for (const [k, v] of Object.entries(propSpec)) if (!k.startsWith('$') && 'default' in v) props[k] = v.default;

let logic = scriptTag[2];
// The prototype is a fixed 390x844 phone frame; the standalone app fills its container.
const fixed = "width: 390px; height: 844px;";
if (!logic.includes(fixed)) throw new Error('Root size string not found; check rootStyle in Main.dc.html');
logic = logic.replace(fixed, 'width: 100%; height: 100%;');

const version = (src.match(/Streakling v([0-9.]+)/) || [])[1] || 'dev';
if (template.includes('</template>')) throw new Error('Template contains </template>');
if (logic.includes('</script')) throw new Error('Logic contains </script');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1">
<meta name="theme-color" content="#F4F3EF">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Streakling">
<meta name="description" content="Streakling: a gamified habit tracker with a pixel hero that levels up with you.">
<title>Streakling</title>
<!-- Generated by scripts/build.mjs from prototype/Main.dc.html (v${version}). Edit the prototype, then rebuild. -->
${helmet.trim()}
<style>
html, body { height: 100%; }
body { margin: 0; background: #0E1013; overflow: hidden; -webkit-tap-highlight-color: transparent; }
#app { position: fixed; inset: 0; overflow: hidden; }
#app > div { width: 100%; height: 100%; }
@media (min-width: 520px) and (min-height: 600px) {
  #app { inset: auto; top: 50%; left: 50%; transform: translate(-50%, -50%); width: 390px; height: min(844px, calc(100vh - 32px)); border-radius: 36px; box-shadow: 0 0 0 10px #24272E, 0 24px 60px rgba(0,0,0,0.5); }
}
#boot-error { position: fixed; inset: 16px; z-index: 10; margin: 0; padding: 16px; background: #fff; color: #B42318; font: 13px/1.5 ui-monospace, monospace; white-space: pre-wrap; overflow: auto; border-radius: 12px; }
</style>
</head>
<body>
<div id="app"></div>
<pre id="boot-error" hidden></pre>
<template id="app-template">
${template}
</template>
<script src="vendor/preact.min.js"></script>
<script src="runtime.js"></script>
<script>
StreaklingBoot({
  template: 'app-template',
  mount: 'app',
  props: ${JSON.stringify(props)},
  component: function () {
${logic.trim()}
    return Component;
  }
});
// Offline support. Pages served over http (except localhost) cannot use a service worker.
if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost')) {
  window.addEventListener('load', function () { navigator.serviceWorker.register('sw.js').catch(function () {}); });
}
</script>
</body>
</html>
`;

writeFileSync(join(root, 'docs/index.html'), html);
console.log('Built docs/index.html (v' + version + ', ' + Math.round(html.length / 1024) + ' KB)');

// Service worker: network first (so updates arrive right away), cached copy when offline.
const sw = `// Generated by scripts/build.mjs (v${version}).
const CACHE = 'streakling-v${version}';
const CORE = ['./', './index.html', './runtime.js', './vendor/preact.min.js', './manifest.webmanifest', './icons/icon-192.png', './icons/icon-512.png', './icons/apple-touch-icon.png', './icons/favicon-32.png'];
const FONTS = /^https:\\/\\/fonts\\.(googleapis|gstatic)\\.com\\//;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('streakling-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  // Fonts: cached copy first, they never change.
  if (FONTS.test(req.url)) {
    e.respondWith(caches.open(CACHE).then(c => c.match(req).then(hit => hit || fetch(req).then(res => { if (res.ok || res.type === 'opaque') c.put(req, res.clone()); return res; }))));
    return;
  }
  if (new URL(req.url).origin !== self.location.origin) return;
  // App files: network first, cache as fallback (also after 4 s without an answer).
  const network = fetch(req).then(res => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return res; });
  const cached = () => caches.match(req, { ignoreSearch: true }).then(hit => hit || (req.mode === 'navigate' ? caches.match('./index.html') : undefined));
  const slow = new Promise(resolve => setTimeout(resolve, 4000)).then(cached);
  e.respondWith(Promise.race([network.catch(cached), slow.then(hit => hit || network)]).then(res => res || network));
});
`;
writeFileSync(join(root, 'docs/sw.js'), sw);
console.log('Built docs/sw.js');

// Static design boards: plain HTML pages, no logic needed.
mkdirSync(join(root, 'docs/design'), { recursive: true });
const boards = { Characters: 'characters', Items: 'items', Fishing: 'fishing' };
for (const [file, slug] of Object.entries(boards)) {
  const b = readFileSync(join(root, `prototype/${file}.dc.html`), 'utf8');
  const bx = between(b, '<x-dc>', '</x-dc>', `<x-dc> in ${file}`);
  if (bx.includes('{{') || bx.includes('<sc-')) throw new Error(`${file} has dynamic parts; it needs the runtime`);
  const title = (b.match(/<title>([^<]*)<\/title>/) || [])[1] || file;
  const width = (b.match(/"\$preview":\{"width":(\d+)/) || [])[1] || '1240';
  const bh = between(bx, '<helmet>', '</helmet>', `<helmet> in ${file}`);
  const body = bx.slice(bx.indexOf('</helmet>') + '</helmet>'.length).trim();
  const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=${width}">
<title>${title} · Streakling design</title>
<!-- Generated by scripts/build.mjs from prototype/${file}.dc.html. -->
${bh.trim()}
</head>
<body>
${body}
</body>
</html>
`;
  writeFileSync(join(root, `docs/design/${slug}.html`), page);
  console.log(`Built docs/design/${slug}.html`);
}
